"""Operator commands, run as the service user with the service environment:

    sudo -u lab-manager /srv/gns3-ro/manager/lab-manager-admin <command>

Commands never print secrets, except `gateway-env`, which writes the gateway's env file to stdout:

    sudo -u lab-manager ./lab-manager-admin gateway-env | install -m 600 /dev/stdin /etc/lab-manager/gateway.env
"""

import argparse
import asyncio
import base64
import json
import ssl
import sys
from urllib.parse import urlsplit

from . import config
from .db import latest_version, migrate


def _settings():
    try:
        return config.load()
    except config.ConfigError as exc:
        raise SystemExit(f"CONFIG_ERROR: {exc}") from exc


async def _with_services(fn):
    from .app import Services

    services = Services(_settings())
    await services.pool.open(wait=True, timeout=10)
    try:
        await services.store.sync_slots(list(services.settings.slots.values()))
        return await fn(services)
    finally:
        await services.close()


def cmd_migrate(args):
    applied = migrate(_settings().database_url)
    print(json.dumps({"applied": applied, "version": latest_version()}))


def cmd_check_config(args):
    s = _settings()
    print(json.dumps({
        "sites": sorted(x.slug for x in s.sites.values()),
        "slots": sorted(s.slots),
        "pve_nodes": list(s.pve_nodes),
        "agent_url_template": s.agent_url_template,
        "slot_code_revision": s.slot_code_revision,
        "agent_start_actions": list(s.agent_start_actions),
        "labs_dir": str(s.labs_dir),
        "images": sorted(s.images) if s.images is not None else None,
        "site_limits": {x.slug: x.limits.public() for x in s.sites.values()},
    }, ensure_ascii=False))


def _slot_ca_b64(path) -> str:
    """The slot CA as one base64 line. The gateway's unit hides /etc/lab-manager from its dynamic
    user, so a path to SLOT_CA_FILE in gateway.env would be unreadable there."""
    try:
        pem = path.read_text("ascii")
        if "-----BEGIN CERTIFICATE-----" not in pem:
            raise ValueError("no PEM certificate in it")
        ssl.create_default_context(cadata=pem)
    except (OSError, ValueError) as exc:  # ssl.SSLError is an OSError
        raise SystemExit(f"CONFIG_ERROR: SLOT_CA_FILE {path} is not a readable PEM CA: {exc}") from exc
    return base64.b64encode(pem.encode("ascii")).decode("ascii")


def gateway_env(s) -> str:
    """Env file of the console gateway from the manager's own config: one source for the slot
    console tokens, the ticket key and the Moodle origins (README §1.1)."""
    missing = sorted(v for v, slot in s.slots.items() if not slot.console_token)
    if missing:
        raise SystemExit(f"CONFIG_ERROR: slots without console_token: {missing}")
    if not s.gateway_internal_url.startswith(("http://127.0.0.1:", "http://localhost:")):
        raise SystemExit("CONFIG_ERROR: GATEWAY_INTERNAL_URL must be http://127.0.0.1:<port> (gateway in this LXC)")
    port = urlsplit(s.gateway_internal_url).port
    slots = {slot.address: slot.console_token for slot in s.slots.values()}
    origins = sorted({f"{u.scheme}://{u.netloc}".lower() for u in map(urlsplit, s.sites)})
    values = {
        "GW_HOST": "127.0.0.1",
        "GW_PORT": str(port),
        "GW_INTERNAL_KEY": s.gateway_internal_key,
        "GW_ALLOWED_ORIGINS": ",".join(origins),
        "GW_SLOTS": json.dumps(slots, separators=(",", ":")),
        "GW_SLOT_SCHEME": "wss" if s.slot_scheme == "https" else "ws",
        "GW_SLOT_CA_B64": _slot_ca_b64(s.slot_ca_file) if s.slot_ca_file else "",
        "GW_ALLOW_PLAINTEXT_SLOTS": "1" if s.allow_plaintext_slots else "0",
    }
    if any("'" in v or "\n" in v for v in values.values()):
        raise SystemExit("CONFIG_ERROR: gateway values must not contain quotes or newlines")
    # Single quotes: systemd's EnvironmentFile parser would strip the double quotes of the JSON.
    lines = ["# Generated by `lab-manager-admin gateway-env`; regenerate after changing slots.json or sites.json."]
    lines += [f"{k}='{v}'" for k, v in values.items()]
    return "\n".join(lines) + "\n"


def cmd_gateway_env(args):
    sys.stdout.write(gateway_env(_settings()))


def cmd_labs(args):
    from .labs import Catalog

    print(json.dumps(Catalog(_settings().labs_dir).check_all(), ensure_ascii=False, indent=1))


def cmd_slots(args):
    async def run(services):
        rows = await services.store.slots()
        for r in rows:
            print(json.dumps({k: r[k] for k in ("vmid", "address", "state", "generation",
                                                "session_id", "student_key", "in_config", "state_message")},
                             ensure_ascii=False, default=str))

    asyncio.run(_with_services(run))


def cmd_slot_state(args):
    """enable: maintenance/failed -> free, after the operator checked the CT and its lab."""

    async def run(services):
        from .ownership import command_scope

        async with services.store.allocation_guard():
            slot = await services.store.slot(args.vmid)
            if slot is None or slot["state"] not in ("free", "failed", "maintenance"):
                raise SystemExit("Slot is in use or unknown")
            if args.state == "free":
                epoch = await services.store.current_epoch()
                with command_scope(epoch, 2 * slot["generation"] + 1):
                    node = await services.pve.find_ct_node(args.vmid)
                    await services.agent.claim(node, args.vmid)
                    state = await services.agent.status(node, args.vmid)
                    if state != "stopped":
                        raise SystemExit(f"CT {args.vmid} is {state} on {node}; stop it first")
                    key = services.settings.placeholder_student_key
                    await services.agent.set_mounts(node, args.vmid, student_key=key, data_mode="ro",
                                                   code_revision=services.settings.slot_code_revision)
                    config = await services.pve.ct_config(args.vmid)
                    if not services.orchestrator.mounts_ok(config, key, read_only=True):
                        raise SystemExit("Parking not confirmed; slot remains unavailable")
                    await services.store.set_slot_admin_state(args.vmid, args.state, args.message, check_epoch=True)
            else:
                await services.store.set_slot_admin_state(args.vmid, args.state, args.message)
        print(json.dumps({"vmid": args.vmid, "state": args.state}))

    asyncio.run(_with_services(run))


def main(argv=None):
    parser = argparse.ArgumentParser(prog="lab_manager.admin")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("migrate").set_defaults(fn=cmd_migrate)
    sub.add_parser("check-config").set_defaults(fn=cmd_check_config)
    sub.add_parser("labs").set_defaults(fn=cmd_labs)
    sub.add_parser("gateway-env").set_defaults(fn=cmd_gateway_env)
    sub.add_parser("slots").set_defaults(fn=cmd_slots)
    for name, state in (("slot-enable", "free"), ("slot-maintenance", "maintenance")):
        p = sub.add_parser(name)
        p.add_argument("vmid", type=int)
        p.add_argument("--message", default="")
        p.set_defaults(fn=cmd_slot_state, state=state)
    args = parser.parse_args(argv)
    args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
