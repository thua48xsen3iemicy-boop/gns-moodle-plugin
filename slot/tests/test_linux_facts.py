M = "@@gns3lab"


def sys_output(hostname="PC1", forward="0", resolv=None, upstream=None):
    text = f"{M} hostname\n{hostname}\n{M} ip_forward\n{forward}\n"
    if resolv is not None:
        text += f"{M} resolv\n{resolv}\n"
    if upstream is not None:
        text += f"{M} upstream\n{upstream}\n"
    return text


