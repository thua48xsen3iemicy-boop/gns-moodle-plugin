def test_linux_sys_reports_the_hostname_forwarding_and_resolver():
    data = parse_linux_sys(sys_output("PC1.lab.local", "1", PLAIN_RESOLV))
    assert data == {
        "hostname": "PC1.lab.local",  # as the kernel has it, an FQDN included
        "ip_forward": True,
        "dns": {"servers": ["10.0.0.53", "8.8.8.8", "fd00::53"], "search": ["lab.local", "corp.local"]},
        "snat": [],  # neither nft nor iptables-save: nothing can translate
    }


def test_the_last_of_search_and_domain_wins_as_in_glibc():
    assert resolver_config(["search a.example b.example", "domain c.example"]) == ([], ["c.example"])
    assert resolver_config(["domain c.example", "search a.example"]) == ([], ["a.example"])
    assert resolver_config(["#nameserver 10.0.0.1", ";nameserver 10.0.0.2", "  nameserver 10.0.0.3  "]) == (
        ["10.0.0.3"], [],
    )


def test_systemd_resolved_reports_the_servers_it_forwards_to():
    data = parse_linux_sys(sys_output(resolv=STUB_RESOLV, upstream=UPSTREAM_RESOLV))
    assert data["dns"] == {"servers": ["10.0.0.1", "1.1.1.1"], "search": ["lab.local"], "resolver": "systemd-resolved"}
    # resolved without a single upstream server: it has nothing to forward to
    empty = parse_linux_sys(sys_output(resolv=STUB_RESOLV, upstream="# no servers\n"))
    assert empty["dns"] == {"servers": [], "search": ["lab.local"], "resolver": "systemd-resolved"}


def test_a_stub_without_the_upstream_file_is_reported_as_it_is():
    data = parse_linux_sys(sys_output(resolv=STUB_RESOLV))
    assert data["dns"] == {"servers": ["127.0.0.53"], "search": ["lab.local"]}


def test_a_stub_next_to_a_real_server_is_not_replaced():
    data = parse_linux_sys(sys_output(resolv="nameserver 127.0.0.53\nnameserver 10.0.0.53\n", upstream=UPSTREAM_RESOLV))
    assert data["dns"] == {"servers": ["127.0.0.53", "10.0.0.53"], "search": []}


def test_no_resolv_conf_is_no_servers():
    assert parse_linux_sys(sys_output())["dns"] == {"servers": [], "search": []}
    assert parse_linux_sys(sys_output(resolv=""))["dns"] == {"servers": [], "search": []}


@pytest.mark.parametrize(
    "stdout",
    [
        "",
        "garbage\n",
        f"{M} hostname\nPC1\n",  # no ip_forward
        sys_output(hostname=""),
        sys_output(forward="yes"),
        sys_output() + f"{M} hostname\nPC2\n",  # a section twice
    ],
)
def test_garbage_is_a_parse_error(stdout):
    with pytest.raises(ParseError):
        parse_linux_sys(stdout)


def test_the_sys_command_reads_the_kernel_and_the_resolver():
    """The command runs in this container as it would in a guest: /proc is real, resolv.conf may be missing."""
    done = subprocess.run(["/bin/sh", "-c", LINUX_SYS_COMMAND], capture_output=True, text=True)
    assert done.returncode == 0, done.stderr
    data = parse_linux_sys(done.stdout)
    with open("/proc/sys/kernel/hostname") as kernel:
        assert data["hostname"] == kernel.read().strip()
    with open("/proc/sys/net/ipv4/ip_forward") as forward:
        assert data["ip_forward"] is (forward.read().strip() != "0")
    assert set(data["dns"]) <= {"servers", "search", "resolver"}


