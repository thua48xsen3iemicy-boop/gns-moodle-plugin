# --- the guest command --------------------------------------------------------------------------------------------

FAKE_IFQUERY = r"""#!/bin/sh
# ifupdown 0.8 as far as the command asks it
case "$*" in
"--no-mappings --list -a") printf 'lo\nens3\n';;
"--no-mappings --list --allow=hotplug") printf 'ens4\n';;
"--no-mappings -v --list -a") echo "ifquery: parsing file $FAKE_DIR/gns3lab" >&2; printf 'lo\nens3\n';;
"--no-mappings ens3") printf 'address: 10.0.0.1\nnetmask: 255.255.255.0\ngateway: 10.0.0.254\nbroadcast: 10.0.0.255\n';;
"--no-mappings ens4"|"--no-mappings lo") ;;
*) echo "ifquery: unexpected $*" >&2; exit 9;;
esac
"""
FAKE_IFUP = r"""#!/bin/sh
echo "$*" > "$FAKE_DIR/ifup.args"
echo 'ip link set dev lo up' >&2
if [ -n "${FAKE_IFUP_ERROR-}" ]; then echo "ifup: $FAKE_IFUP_ERROR" >&2; exit 1; fi
"""


def tools(tmp_path, active=(), netplan=False, ifupdown=True):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir(exist_ok=True)
    scripts = {"systemctl": "#!/bin/sh\ncase \" $FAKE_ACTIVE \" in *\" $3 \"*) exit 0;; esac\nexit 3\n"}
    if ifupdown:
        scripts.update(ifquery=FAKE_IFQUERY, ifup=FAKE_IFUP)
    if netplan:
        scripts["netplan"] = "#!/bin/sh\nexit 0\n"
    for name, text in scripts.items():
        path = bin_dir / name
        path.write_text(text)
        path.chmod(path.stat().st_mode | stat.S_IXUSR)
    (tmp_path / "gns3lab").write_text(
        "auto ens3\niface ens3 inet static\n    address 10.0.0.1/24\n    gateway 10.0.0.254\n\n"
        "allow-hotplug ens4\n  iface ens4 inet dhcp\n# iface ens4 inet static\n"
    )
    return {"PATH": f"{bin_dir}:/usr/bin:/bin", "FAKE_DIR": str(tmp_path), "FAKE_ACTIVE": " ".join(active)}


def run_config(env):
    done = subprocess.run(["/bin/sh", "-c", LINUX_CONFIG_COMMAND], capture_output=True, text=True, env=env)
    assert done.returncode == 0, done.stderr
    return parse_linux_config(done.stdout)["net_saved"]


def test_the_config_command_asks_ifupdown_and_only_with_no_act(tmp_path):
    env = tools(tmp_path)
    saved = run_config(env)
    assert saved == {
        "mechanism": "ifupdown", "ok": True,
        "interfaces": [
            {"name": "ens3", "method": "static", "ipv4": ["10.0.0.1/24"], "gateway": "10.0.0.254"},
            {"name": "ens4", "method": "dhcp", "ipv4": []},
            {"name": "lo", "method": "loopback", "ipv4": []},
        ],
    }
    args = (tmp_path / "ifup.args").read_text().split()
    assert args[:4] == ["--no-act", "--force", "--no-mappings", "--no-scripts"]
    assert sorted(args[4:]) == ["ens3", "ens4", "lo"]
    env["FAKE_IFUP_ERROR"] = "missing required variable: address"
    assert run_config(env)["message"] == "missing required variable: address"


