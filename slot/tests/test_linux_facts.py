def nat_output(**sections):
    return sys_output() + "".join(f"{M} {name} {rc}\n{text}\n" for name, (rc, text) in sections.items())


def test_nft_rules_of_the_postrouting_nat_chains_in_order():
    assert parse_linux_sys(nat_output(nft=("0", NFT_NATIVE)))["snat"] == [
        {"action": "masquerade", "out": "eth0", "src": "192.168.1.0/24", "exact": True},
        {"action": "accept", "out": None, "src": "192.168.1.5/32", "exact": True},
    ]


def test_iptables_nft_rules_seen_through_nft_and_through_iptables_save():
    expected = [
        {"action": "masquerade", "out": "ens3", "src": "10.0.0.0/8", "exact": True},  # a comment is no condition
        {"action": "snat", "out": None, "src": None, "exact": False},  # TCP only: not read, the benefit of the doubt
    ]
    assert parse_linux_sys(nat_output(nft=("0", NFT_IPTABLES)))["snat"] == expected
    assert parse_linux_sys(nat_output(iptables=("0", IPTABLES_SAVE)))["snat"] == expected


@pytest.mark.parametrize("line, rule", [
    ("-A POSTROUTING -o eth+ -j MASQUERADE", {"action": "masquerade", "out": None, "src": None, "exact": False}),
    ("-A POSTROUTING ! -s 10.0.0.0/8 -j MASQUERADE", {"action": "masquerade", "out": None, "src": "10.0.0.0/8",
                                                      "exact": False}),
    ("-A POSTROUTING -j DOCKER", {"action": "other", "out": None, "src": None, "exact": True}),
    ("-A POSTROUTING -s 192.168.0.0/16 -j RETURN", {"action": "return", "out": None, "src": "192.168.0.0/16",
                                                     "exact": True}),
])
def test_iptables_save_lines(line, rule):
    assert parse_linux_sys(nat_output(iptables=("0", f"*nat\n{line}\nCOMMIT\n")))["snat"] == [rule]


@pytest.mark.parametrize("sections", [
    {"nft": ("1", "")},  # nft refused: not root, no netlink
    {"nft": ("0", NFT_NATIVE[:300])},  # cut at the size limit
    {"nft": ("0", '{"nftables": 5}')},
    {"nft": ("0", NFT_NATIVE), "iptables": ("1", "")},
])
def test_nat_that_cannot_be_read_is_unknown_and_the_hostname_stays(sections):
    data = parse_linux_sys(nat_output(**sections))
    assert "snat" not in data and data["hostname"] == "PC1"


def test_an_empty_ruleset_is_no_nat():
    assert parse_linux_sys(nat_output(nft=("0", "")))["snat"] == []
    assert parse_linux_sys(nat_output(nft=("0", '{"nftables": []}')))["snat"] == []
